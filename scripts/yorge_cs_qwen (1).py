def translate_qwen(texts, prompt_fn, batch_size=4):
    results = []
    batches = [texts[i:i+batch_size] for i in range(0, len(texts), batch_size)]

    for batch in tqdm(batches, desc="Qwen2.5-3B translating", unit="batch"):
        prompts = [
            tokenizer.apply_chat_template(
                prompt_fn(text),
                tokenize=False,
                add_generation_prompt=True
            )
            for text in batch
        ]

        inputs = tokenizer(
            prompts,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=512
        ).to(model.device)

        outputs = model.generate(
            **inputs,
            max_new_tokens=128,
            do_sample=False,
            temperature=None,
            top_p=None,
            pad_token_id=tokenizer.eos_token_id
        )

        decoded = tokenizer.batch_decode(
            outputs[:, inputs['input_ids'].shape[1]:],
            skip_special_tokens=True
        )
        results.extend([d.strip() for d in decoded])

    return results

