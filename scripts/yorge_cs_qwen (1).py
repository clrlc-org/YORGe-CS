# Translation function
def translate_finetuned(texts, batch_size=4):
    results = []
    batches = [texts[i:i+batch_size] for i in range(0, len(texts), batch_size)]

    for batch in tqdm(batches, desc="Qwen2.5-3B LoRA translating", unit="batch"):
        prompts = [
            tokenizer.apply_chat_template(
                [
                    {
                        "role": "system",
                        "content": (
                            "You are a multilingual translator. "
                            "The following sentence is written in Yoruba-German "
                            "code-switched form, where Yorùbá is the matrix language "
                            "and German is the embedded language. Translate it to "
                            "English. Output only the English translation, nothing else."
                        )
                    },
                    {"role": "user", "content": text}
                ],
                tokenize=False,
                add_generation_prompt=True
            )
            for text in batch
        ]

        inputs = tokenizer(
            prompts, return_tensors="pt", padding=True,
            truncation=True, max_length=512
        ).to(ft_model.device)

        outputs = ft_model.generate(
            **inputs, max_new_tokens=128, do_sample=False,
            temperature=None, top_p=None,
            pad_token_id=tokenizer.eos_token_id
        )

        decoded = tokenizer.batch_decode(
            outputs[:, inputs['input_ids'].shape[1]:],
            skip_special_tokens=True
        )
        results.extend([d.strip() for d in decoded])

    return results

