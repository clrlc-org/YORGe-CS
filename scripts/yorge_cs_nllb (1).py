"""LoRA fine-tuning"""

class YorGeSeq2SeqDataset(TorchDataset):
    def __init__(self, sources, targets, tokenizer, src_lang="yor_Latn",
                 tgt_lang="eng_Latn", max_length=256):
        tokenizer.src_lang = src_lang
        self.inputs = tokenizer(
            sources, truncation=True, padding="max_length",
            max_length=max_length, return_tensors="pt"
        )

        labels = tokenizer(
            targets, truncation=True, padding="max_length",
            max_length=max_length, return_tensors="pt"
        )


        label_ids = labels['input_ids'].clone()
        label_ids[label_ids == tokenizer.pad_token_id] = -100
        self.labels = label_ids

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        return {
            'input_ids'     : self.inputs['input_ids'][idx],
            'attention_mask': self.inputs['attention_mask'][idx],
            'labels'        : self.labels[idx]
        }

