def evaluate(preds, refs, label):
    b = bleu_metric.corpus_score(preds, [refs])
    c = chrf_metric.corpus_score(preds, [refs])
    m = np.mean([
        meteor_score([ref.split()], pred.split())
        for ref, pred in zip(refs, preds)
    ])
    print(f"{label:<35} {b.score:<10.2f} {c.score:<10.2f} {m:.4f}")
    return b.score, c.score, m

def translate_nllb(texts, src_lang="yor_Latn", tgt_lang="eng_Latn", batch_size=8):
    tokenizer.src_lang = src_lang
    forced_bos_token_id = tokenizer.convert_tokens_to_ids(tgt_lang)
    results = []
    batches = [texts[i:i+batch_size] for i in range(0, len(texts), batch_size)]

    for batch in tqdm(batches, desc=f"NLLB {src_lang}\u2192{tgt_lang}", unit="batch"):
        inputs = tokenizer(
            batch, return_tensors="pt", padding=True,
            truncation=True, max_length=256
        ).to(model.device)

        outputs = model.generate(
            **inputs,
            forced_bos_token_id=forced_bos_token_id,
            max_new_tokens=256
        )
        decoded = tokenizer.batch_decode(outputs, skip_special_tokens=True)
        results.extend(decoded)

    return results

